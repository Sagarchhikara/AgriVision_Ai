"""
backend/services/llm/fake.py

A provider that returns canned output instead of calling anything.

Two jobs:
  - Tests: no network, no API key, no cost, and deterministic output. The
    scripted-response list lets a test drive the malformed-JSON retry path and
    the provider-failure path without monkeypatching internals.
  - Local demos: the default provider in configs/config.yaml, so a fresh clone
    can exercise /report and /predict?include_report=true immediately. Its
    output is deliberately, visibly labelled as a sample so nobody mistakes a
    fake report for a real diagnosis.
"""

from __future__ import annotations

import json
from collections.abc import Sequence

from backend.core.logging import get_logger
from backend.services.llm.base import LLMProvider

logger = get_logger(__name__)

SAMPLE_REPORT: dict = {
    "disease_name": "Sample diagnosis (fake provider)",
    "crop": "Sample crop",
    "summary": (
        "This is placeholder text from the fake LLM provider, not a real diagnosis. "
        "Set AGRIVISION_LLM_PROVIDER to gemini or openai, with the matching API key "
        "in the environment, to generate a real report."
    ),
    "severity": "low",
    "severity_reason": "Placeholder text carries no severity assessment.",
    "symptoms_to_check": ["Placeholder symptom -- no real observation was made."],
    "treatment": {
        "organic": ["Placeholder organic step."],
        "chemical": [],
    },
    "prevention": ["Placeholder prevention step."],
    "when_to_consult_expert": (
        "Always consult your local agricultural extension officer before acting on "
        "any report, and note that this particular report is sample output."
    ),
    "confidence_note": "Generated by the fake provider; it reflects no analysis of the image.",
}


class FakeProvider(LLMProvider):
    """Returns canned output, optionally scripted per call."""

    name = "fake"

    def __init__(self, responses: Sequence[str | Exception] | None = None):
        """
        Args:
            responses: optional scripted results, consumed one per call. A string
                is returned as the model's raw output; an Exception is raised.
                Once exhausted the last entry repeats, so a test can script a
                single failure without having to predict the total call count.
                Defaults to always returning SAMPLE_REPORT.
        """
        self._responses = list(responses) if responses else None
        self.call_count = 0
        self.prompts: list[tuple[str, str]] = []

    async def generate(self, system_prompt: str, user_prompt: str) -> str:
        self.prompts.append((system_prompt, user_prompt))
        index = self.call_count
        self.call_count += 1

        if self._responses is None:
            return json.dumps(SAMPLE_REPORT)

        result = self._responses[min(index, len(self._responses) - 1)]
        if isinstance(result, Exception):
            raise result
        return result
